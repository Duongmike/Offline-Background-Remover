"""Generate the project's original synthetic alpha-regression starter dataset."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter


ROOT = Path(__file__).resolve().parent.parent / "quality_dataset" / "starter"
SIZE = 256


def _radial_mask(radius: float, softness: float = 0.0) -> Image.Image:
    y, x = np.ogrid[:SIZE, :SIZE]
    distance = np.sqrt((x - SIZE / 2) ** 2 + (y - SIZE / 2) ** 2)
    if softness <= 0:
        alpha = (distance <= radius).astype(np.uint8) * 255
    else:
        alpha = np.clip((radius + softness - distance) / softness, 0.0, 1.0) * 255
    return Image.fromarray(alpha.astype(np.uint8), "L")


def _draw_mask(kind: str) -> Image.Image:
    if kind == "hard_circle":
        return _radial_mask(72)
    if kind == "soft_edge":
        return _radial_mask(68, 18)
    mask = Image.new("L", (SIZE, SIZE), 0)
    draw = ImageDraw.Draw(mask)
    if kind == "thin_strands":
        draw.ellipse((70, 65, 186, 205), fill=255)
        for offset in range(-55, 56, 9):
            draw.line((128 + offset // 2, 80, 128 + offset, 24), fill=230, width=2)
    elif kind == "translucent":
        draw.rounded_rectangle((54, 48, 202, 210), radius=28, fill=118, outline=235, width=6)
    elif kind == "low_contrast":
        draw.polygon(((128, 34), (218, 202), (38, 202)), fill=255)
    elif kind == "green_foreground":
        draw.ellipse((50, 40, 206, 216), fill=255)
        draw.rectangle((122, 20, 134, 236), fill=255)
    elif kind == "multiple_objects":
        draw.ellipse((26, 52, 118, 170), fill=255)
        draw.rounded_rectangle((142, 92, 232, 220), radius=18, fill=210)
    elif kind == "fine_geometry":
        draw.rectangle((116, 28, 140, 228), fill=255)
        draw.rectangle((28, 116, 228, 140), fill=255)
        draw.ellipse((74, 74, 182, 182), outline=255, width=5)
    else:
        raise ValueError(f"Unknown synthetic case: {kind}")
    return mask


def _create_input(kind: str, mask: Image.Image, index: int) -> Image.Image:
    yy, xx = np.mgrid[:SIZE, :SIZE]
    background = np.empty((SIZE, SIZE, 3), dtype=np.uint8)
    background[:, :, 0] = (35 + xx // 2 + index * 7) % 255
    background[:, :, 1] = (150 + yy // 4 + index * 11) % 255
    background[:, :, 2] = (205 - xx // 3 + index * 5) % 255
    if kind == "low_contrast":
        foreground_color = (92, 174, 184)
    elif kind == "green_foreground":
        foreground_color = (24, 155, 74)
        background[:, :, :] = (40, 180, 95)
    else:
        foreground_color = (225, 72 + index * 8, 48 + index * 10)
    source = Image.fromarray(background, "RGB")
    foreground = Image.new("RGB", (SIZE, SIZE), foreground_color)
    try:
        return Image.composite(foreground, source, mask)
    finally:
        source.close()
        foreground.close()


def main() -> int:
    """Write reproducible PNG inputs, alpha masks, and licensed manifest."""
    inputs = ROOT / "inputs"
    masks = ROOT / "ground_truth"
    inputs.mkdir(parents=True, exist_ok=True)
    masks.mkdir(parents=True, exist_ok=True)
    cases = []
    kinds = ("hard_circle", "soft_edge", "thin_strands", "translucent", "low_contrast", "green_foreground", "multiple_objects", "fine_geometry")
    for index, kind in enumerate(kinds):
        mask = _draw_mask(kind)
        source = _create_input(kind, mask, index)
        try:
            source.save(inputs / f"{kind}.png", compress_level=9)
            mask.save(masks / f"{kind}.png", compress_level=9)
        finally:
            source.close()
            mask.close()
        cases.append({
            "id": kind,
            "category": kind,
            "input": f"inputs/{kind}.png",
            "ground_truth": f"ground_truth/{kind}.png",
            "prediction": f"{kind}.png",
            "license": "CC0-1.0",
            "source": "Generated by scripts/generate_quality_starter.py",
        })
    manifest = {
        "schema_version": 1,
        "name": "Offline Background Remover synthetic starter",
        "license": "CC0-1.0",
        "limitations": "Synthetic regression fixtures; not evidence of real-world segmentation quality.",
        "thresholds": {"max_mae": 0.08, "min_iou": 0.70, "min_f1": 0.78},
        "cases": cases,
    }
    (ROOT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
