from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path

import numpy as np
from PIL import Image

from image_tool.quality import alpha_metrics, evaluate_predictions, load_manifest, quality_gate


class AlphaMetricTests(unittest.TestCase):
    def test_identical_masks_have_perfect_metrics(self) -> None:
        mask = np.asarray([[0, 127], [128, 255]], dtype=np.uint8)
        metrics = alpha_metrics(mask, mask)
        self.assertEqual(0.0, metrics.mae)
        self.assertEqual(0.0, metrics.sad)
        self.assertEqual(1.0, metrics.iou)
        self.assertEqual(1.0, metrics.f1)

    def test_quality_gate_reports_regression(self) -> None:
        report = {"aggregate": {"mae": 0.2, "sad": 10.0, "iou": 0.6, "f1": 0.7}}
        failures = quality_gate(report, {"max_mae": 0.1, "min_iou": 0.8, "min_f1": 0.75})
        self.assertEqual(3, len(failures))

    def test_manifest_requires_attribution_and_evaluates_alpha(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            inputs = root / "inputs"
            truth = root / "truth"
            predictions = root / "predictions"
            inputs.mkdir()
            truth.mkdir()
            predictions.mkdir()
            Image.new("RGB", (2, 2), "white").save(inputs / "case.png")
            Image.fromarray(np.asarray([[0, 255], [0, 255]], dtype=np.uint8), "L").save(truth / "case.png")
            output = Image.new("RGBA", (2, 2), "red")
            try:
                with Image.open(truth / "case.png") as alpha:
                    output.putalpha(alpha)
                output.save(predictions / "case.png")
            finally:
                output.close()
            manifest = {
                "schema_version": 1,
                "name": "fixture",
                "license": "CC0-1.0",
                "cases": [{
                    "id": "case", "category": "simple", "input": "inputs/case.png",
                    "ground_truth": "truth/case.png", "prediction": "case.png", "source": "generated by test",
                }],
            }
            manifest_path = root / "manifest.json"
            manifest_path.write_text(json.dumps(manifest), encoding="utf-8")
            name, cases = load_manifest(manifest_path)
            report = evaluate_predictions(name, cases, predictions)
            self.assertEqual(1, report["case_count"])
            self.assertEqual(1.0, report["aggregate"]["iou"])


if __name__ == "__main__":
    unittest.main()
